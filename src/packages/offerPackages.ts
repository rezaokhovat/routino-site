function uniqueJobTitles(titles: string[]) {
  const seen = new Set<string>()
  const result: string[] = []
  for (const title of titles) {
    const key = title.replace(/ي/g, 'ی').replace(/ك/g, 'ک').replace(/‌/g, '').replace(/\s+/g, ' ').trim()
    if (!key || seen.has(key)) continue
    seen.add(key)
    result.push(title.trim())
  }
  return result
}

